/*
 * 台本とは別の API 呼び出しで使う。generateOutline.ts が唯一の使い手なので、
 * 台本プロンプト（math.ts）とは分けておく。
 */
/**
 * 冒頭には実際の問題を置く余地があり、条件を落とすと答えが変わり得る。完全な条件と問いは既存の
 * 文字列チャネルに保つ。明示的な番号なら、台本の 19-field schema を増やさず全設問を区別できる。
 * 1 問だけでも (1) を付け、新しいデータが旧来の最終行規約に依存しないようにする。
 */
export const OUTLINE_RULE = `# outline（冒頭と一覧に出す問題文）
topic の設定・条件・すべての問いを、省略せず読みやすい順に整える。

- 1行1つの意味のまとまり。目安は4〜10行、1行25〜45文字。短い問題は1行でもよい。
  行数・文字数を守るために情報を削らない。長い文は画面で折り返される。
- 対象の定義、数値、範囲、単位、場合分け、条件どうしの関係をすべて残す。
  「〜である」「〜とする」などの文を使い、体言止めに縮めない。
  元の文を活かし、単独で読んでも何の条件か分かる形にする。
- 共通の設定・条件を先に書き、その後に問われていることをすべて並べる。
- 問いは各行の先頭に半角の (1) (2) のような番号を付ける。単問でも (1) を付ける。
  元の設問番号と順番を保つ。番号がない複数の問いは入力順に採番する。
  1つの問いを1項目とし、「何を」「どうするか」（求めよ・示せ・証明せよ）まで書く。
  問い固有の条件はその問いに含め、別の共通条件にしない。
- 条件の行頭には番号も「・」「-」も付けない。問い以外に設問番号を使わない。
- 数式は topic と同じ $...$ で囲んだ LaTeX のまま写し、式の途中で分断しない。
  地の文・日本語、設問番号、単位（km/h）、日付（9/8）は絶対に $ で囲まない。
  $ は数式の境界だけに使い、表示用の $$ は使わない。
- 問題に無い条件・解き方・答えは足さない。解く方針の①②③もここには書かない。
  outline は最初の問題文専用であり、各設問の方針は別のstep / bulletsシーンに置く。

    入力: 円に内接する四角形ABCDにおいて、AB = BC = 7, CD = 5, DA = 3
          であるとき、cos Bの値を求めなさい。
    outline: "四角形$ABCD$は円に内接している。\\n辺の長さは $AB = BC = 7, CD = 5, DA = 3$ である。\\n(1) $\\cos B$の値を求めなさい。"

    入力: 関数f(x)=x^2-4x+3について、(1) f(x)=0を解け。(2) 0≦x≦3での最小値を求めよ。
    outline: "関数$f(x)=x^2-4x+3$について、次の問いに答えよ。\\n(1) $f(x)=0$を解け。\\n(2) $0\\le x\\le 3$における$f(x)$の最小値を求めよ。"

    入力: ∫_0^π x sinx/(1+cos^2x) dx を求めよ。
    outline: "(1) $\\int_0^\\pi \\frac{x\\sin x}{1+\\cos^2 x}\\,dx$ を求めよ。"

概念の説明（「とは」「教えて」）なら、扱う内容を先に説明し、
最後に「何を理解するか」を (1) から始まる問いとして書く。`;
